#!/usr/bin/env bash
# Opens a pull request to microsoft/winget-pkgs adding an mvm release's
# manifests (implementation plan 0.3b). It writes through GitHub's API to the
# token owner's fork, so nothing large is cloned.
# Usage: submit.sh <version> <dist dir holding the Windows zip>
# Needs GH_TOKEN with public_repo scope, and a fork of microsoft/winget-pkgs.
set -euo pipefail
version="$1"; dist="$2"
id="benallfree.mvm"
owner="$(gh api user -q .login)"
zip="mvm-$version-x86_64-pc-windows-msvc.zip"
url="https://github.com/benallfree/mvm/releases/download/mvm-v$version/$zip"
sha="$(sha256sum "$dist/$zip" | cut -d' ' -f1 | tr a-f A-F)"
dir="manifests/b/benallfree/mvm/$version"
branch="mvm-$version"

installer="PackageIdentifier: $id
PackageVersion: $version
InstallerType: zip
NestedInstallerType: portable
Installers:
- Architecture: x64
  NestedInstallerFiles:
  - RelativeFilePath: mvm-$version-x86_64-pc-windows-msvc\\mvm.exe
    PortableCommandAlias: mvm
  InstallerUrl: $url
  InstallerSha256: $sha
ManifestType: installer
ManifestVersion: 1.6.0
"
locale="PackageIdentifier: $id
PackageVersion: $version
PackageLocale: en-US
Publisher: Ben Allfree
PublisherUrl: https://github.com/benallfree
PackageName: mvm
PackageUrl: https://github.com/benallfree/mvm
License: MIT
LicenseUrl: https://github.com/benallfree/mvm/blob/main/LICENSE
ShortDescription: The MVM command-line tool. Build applets, run simulated meshes, and manage nodes.
Moniker: mvm
ReleaseNotesUrl: https://github.com/benallfree/mvm/releases/tag/mvm-v$version
ManifestType: defaultLocale
ManifestVersion: 1.6.0
"
version_yaml="PackageIdentifier: $id
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
"

# Start a branch in the fork from upstream's current master.
gh api -X POST "repos/$owner/winget-pkgs/merge-upstream" -f branch=master >/dev/null
base="$(gh api repos/microsoft/winget-pkgs/git/ref/heads/master -q .object.sha)"
gh api -X POST "repos/$owner/winget-pkgs/git/refs" -f "ref=refs/heads/$branch" -f "sha=$base" >/dev/null
put() {
  gh api -X PUT "repos/$owner/winget-pkgs/contents/$dir/$1" \
    -f "message=New version: $id version $version" -f "branch=$branch" \
    -f "content=$(printf '%s' "$2" | base64 | tr -d '\n')" >/dev/null
}
put "$id.installer.yaml" "$installer"
put "$id.locale.en-US.yaml" "$locale"
put "$id.yaml" "$version_yaml"
gh pr create --repo microsoft/winget-pkgs --head "$owner:$branch" --base master \
  --title "New version: $id version $version" \
  --body "Adds mvm $version, the MVM command-line tool (https://github.com/benallfree/mvm). Manifests generated by packaging/winget/submit.sh."
