#!/usr/bin/env python3
"""Build the test applets as position-independent images with manifests (rounds 7b, 7c).

Each applet is linked once by `chunker link-pic`, with no base address:
- `guest-image/<x>.bin`: its flash image (code + rodata), runnable anywhere;
- `guest-image/<x>.static`, `<x>.bulk`: the initial bytes of its gp window
  and bulk segment (round 7c: the chunker puts each static in one of them);
- a manifest in `guest-image/applets.rs`: each segment's size, alignment and
  init bytes, bulk slots, data relocations, imports and exports (with full
  names), entry offsets. Imports and exports are read here from the applet's
  own tables, so the kernel never reads guest memory to learn an applet's
  interface.

It also checks (test 7) that the 7c applets' writable statics carry no
attributes: placement is the chunker's job, never the developer's.

The applets are built with `-C code-model=medium` (PC-relative), which link-pic
requires; references to statics are rewritten to be gp-relative.
"""
import json, os, re, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CHUNKER = os.path.join(ROOT, "chunker", "target", "release", "chunker")
OUT = os.path.join(HERE, "guest-image")
sys.path.insert(0, os.path.join(ROOT, "abi"))

# (name, entry functions, exports table or None, statics whose offsets the tests need)
APPLETS = [
    ("h", ["h_hello", "h_timer", "h_nop_loop", "h_empty_loop", "h_uart_loop"], None, []),
    ("a", [], "A_EXPORTS", []),
    ("a2", [], "A2_EXPORTS", []),
    ("b", ["b_echo_once", "b_echo_loop", "b_local_loop", "b_loud", "b_recurse"], None, []),
    ("m", ["m_main"], None, []),
    ("s1", [], "S1_EXPORTS", []),
    ("s2", [], "S2_EXPORTS", []),
    ("s3", [], None, []),
    ("c", ["c_inc", "c_addr", "c_owner", "c_table_sum", "c_print"], None, ["C_COUNT"]),
    ("d", ["d_fill", "d_sum", "d_kernel_sum", "d_addr", "d_owner", "d_squares_sum", "d_bump", "d_tail", "d_ptrs_ok", "d_ptr_set", "d_corners_set",
           "d_corners_get", "d_gp_loop", "d_bulk_loop", "d_none_loop"], None, []),
    ("e", ["e_sum", "e_fill"], None, []),
]
# Ordinary (un-annotated, so mangled) statics whose placement the tests need:
# (applet, const name, a substring of the mangled symbol).
PLACED = [("d", "WORDS", "5WORDS"), ("d", "FILLS", "5FILLS"), ("d", "SQUARES", "7SQUARES"), ("d", "SEED", "4SEED"), ("d", "TAIL", "4TAIL"), ("d", "FILLS_PTRS", "10FILLS_PTRS"), ("d", "WORDS_PTR", "9WORDS_PTR")]
BULK_SRC = os.path.join(ROOT, "guest", "applets", "src", "bulk.rs")
THRESHOLD = int(os.environ.get("BULK_THRESHOLD", "256"))


def check_no_annotations():
    """Test 7: every writable static in bulk.rs is a plain `static mut` with no
    attribute, and nothing in the file names a section."""
    lines = open(BULK_SRC).read().splitlines()
    statics, bad = 0, []
    for i, l in enumerate(lines):
        if re.match(r"\s*(pub\s+)?static\s+mut\s", l):
            statics += 1
            j = i - 1
            while j >= 0 and lines[j].strip().startswith("///"):
                j -= 1
            if j >= 0 and lines[j].strip().startswith("#["):
                bad.append(l.strip())
    for l in lines:
        if l.strip().startswith("//"):
            continue
        if re.search(r"link_section|#\[used\]|export_name", l):
            bad.append(l.strip())
    return statics, bad
# Applets that get a second copy of their image in flash (position-independence test).
COPIES = ["c", "d"]


def fnv1a64(b):
    h = 0xCBF29CE484222325
    for x in b:
        h = ((h ^ x) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def link(inputs, entries, out):
    args = [CHUNKER, "link-pic", "--bulk-threshold", str(THRESHOLD), "-o", out]
    for e in entries:
        args += ["--entry", e]
    r = subprocess.run(args + inputs, capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"chunker link-pic failed for {entries}: {r.stderr}")
    return json.load(open(out + ".json")), r.stdout.strip()


def table(flash, off, entry_size):
    """(count, [entry bytes]) of an import/export table at flash offset `off`."""
    (count,) = struct.unpack_from("<I", flash, off)
    return [flash[off + 8 + entry_size * i: off + 8 + entry_size * (i + 1)] for i in range(count)]


def name_at(flash, ptr, ln):
    return flash[ptr:ptr + ln].decode()


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    subprocess.run(["cargo", "build", "-q", "--release"], cwd=os.path.join(ROOT, "chunker"), check=True)
    env = dict(os.environ, PKG="applets", BUILD_STD="1", CODE_MODEL="medium")
    inputs = subprocess.run([os.path.join(ROOT, "guest", "build.sh")], env=env,
                            capture_output=True, text=True, check=True).stdout.split()
    os.makedirs(OUT, exist_ok=True)
    rs = ["// Generated by meshops/build_applets.py. Do not edit.",
          "use mvm_kernel::{DataReloc, Export, Import, Manifest, Seg, Segment};",
          "",
          "/// Flash images are 16-byte aligned (include_bytes! alone gives align 1).",
          "#[repr(C, align(16))]",
          "pub struct Img<const N: usize>(pub [u8; N]);"]
    for name, funcs, exports, statics in APPLETS:
        imports = name.upper() + "_IMPORTS"
        entries = [imports] + ([exports] if exports else []) + funcs + statics
        base = os.path.join(OUT, name)
        j, summary = link(inputs, entries, base)
        flash = open(base + ".bin", "rb").read()
        os.remove(base + ".json")
        e = j["entries"]
        imps = []
        for ent in table(flash, e[imports][1], 16):
            h, p, ln = struct.unpack("<QII", ent)
            imps.append((h, name_at(flash, p, ln)))
        exps = []
        if exports:
            for ent in table(flash, e[exports][1], 24):
                h, f, p, ln, _ = struct.unpack("<QIIII", ent)
                exps.append((h, name_at(flash, p, ln), f))
        rs.append(f"pub mod {name} {{")
        rs.append("    use super::*;")
        rs.append(f"    pub static IMAGE: Img<{len(flash)}> = Img(*include_bytes!(\"{name}.bin\"));")
        if name in COPIES:
            rs.append(f"    /// A second copy of the same bytes at another flash address.")
            rs.append(f"    pub static IMAGE_COPY: Img<{len(flash)}> = Img(*include_bytes!(\"{name}.bin\"));")
        gp_init = os.path.getsize(base + ".static")
        bulk_init = os.path.getsize(base + ".bulk")
        rs.append(f"    pub static GP_INIT: [u8; {gp_init}] = *include_bytes!(\"{name}.static\");")
        rs.append(f"    pub static BULK_INIT: [u8; {bulk_init}] = *include_bytes!(\"{name}.bulk\");")
        rs.append("    pub static IMPORTS: [Import; %d] = [%s];" % (len(imps), ", ".join(
            f"Import {{ hash: {h:#x}, name: {rs_str(n)} }}" for h, n in imps)))
        rs.append("    pub static EXPORTS: [Export; %d] = [%s];" % (len(exps), ", ".join(
            f"Export {{ hash: {h:#x}, name: {rs_str(n)}, entry: {f} }}" for h, n, f in exps)))
        seg = {"flash": "Seg::Flash", "gp": "Seg::Gp", "bulk": "Seg::Bulk"}
        rs.append("    pub static DATA_RELOCS: [DataReloc; %d] = [%s];" % (len(j["data_relocs"]), ", ".join(
            f"DataReloc {{ seg: {seg[sg]}, at: {a}, to: {seg[t]}, off: {o} }}" for sg, a, t, o in j["data_relocs"])))
        rs.append("    pub static MANIFEST: Manifest = Manifest {")
        rs.append("        image: &IMAGE.0,")
        rs.append(f"        gp: Segment {{ size: {j['gp_size']}, align: {j['gp_align']}, init: &GP_INIT }},")
        rs.append(f"        bulk: Segment {{ size: {j['bulk_size']}, align: {j['bulk_align']}, init: &BULK_INIT }},")
        rs.append(f"        bulk_slots: {j['bulk_slots']},")
        rs.append("        data_relocs: &DATA_RELOCS,")
        rs.append("        imports: &IMPORTS,")
        rs.append("        exports: &EXPORTS,")
        rs.append("    };")
        for f in funcs:
            rs.append(f"    pub const {f[len(name) + 1:].upper()}: u32 = {e[f][1]};")
        for st in statics:
            rs.append(f"    pub const STATIC_{st[len(name) + 1:].upper()}: u32 = {e[st][1]};")
        rs.append(f"    pub const ABS_FLASH_POINTERS: usize = {len(j['abs_flash'])};")
        rs.append(f"    pub const GP_REWRITES: usize = {j['gp_rewrites']};")
        rs.append(f"    pub const BULK_REWRITES: usize = {j['bulk_rewrites']};")
        placed = j["placed"]
        nbulk = sum(1 for p in placed if p[2] == "bulk")
        rs.append(f"    pub const STATICS: usize = {len(placed)};")
        rs.append(f"    pub const STATIC_BYTES: u32 = {sum(p[1] for p in placed)};")
        rs.append(f"    pub const BULK_STATICS: usize = {nbulk};")
        rs.append(f"    pub const PROMOTED: usize = {len(j['promoted'])};")
        rs.append(f"    pub const SPILLED: usize = {sum(1 for p in placed if p[4] == 'spill')};")
        for app, const, frag in PLACED:
            if app == name:
                hit = [p for p in placed if frag in p[0]]
                if len(hit) != 1:
                    sys.exit(f"applet {name}: static {const} not found once in {[p[0] for p in placed]}")
                rs.append(f"    pub const {const}_IN_BULK: bool = {str(hit[0][2] == 'bulk').lower()};")
                rs.append(f"    pub const {const}_OFF: u32 = {hit[0][3]};")
        rs.append("}")
        if placed:
            summary += "\n    placement (threshold %d): " % THRESHOLD + ", ".join(
                f"{p[1]}B->{p[2]}{'(' + p[4] + ')' if p[4] else ''}" for p in placed[:6]) + (
                f", ... ({len(placed)} statics)" if len(placed) > 6 else "")
        # Imports must hash to their names (the kernel checks again at load).
        bad = [n for h, n in imps if fnv1a64(n.encode()) != h and name not in ("s3",)]
        print(f"applet {name}: {summary}{'  (forged imports: ' + str(bad) + ')' if bad else ''}")
    statics, bad = check_no_annotations()
    if bad:
        sys.exit(f"bulk.rs: statics must be ordinary (no attributes): {bad}")
    rs.append(f"/// Test 7: writable statics in guest/applets/src/bulk.rs, all without attributes.")
    rs.append(f"pub const PLAIN_STATICS: usize = {statics};")
    rs.append(f"pub const ANNOTATED_STATICS: usize = {len(bad)};")
    print(f"test 7: {statics} writable statics in bulk.rs, {len(bad)} annotated")
    open(os.path.join(OUT, "applets.rs"), "w").write("\n".join(rs) + "\n")
    for stale in ("applets.bin",):
        p = os.path.join(OUT, stale)
        if os.path.exists(p):
            os.remove(p)


if __name__ == "__main__":
    main()
