#!/usr/bin/env python3
"""Link the round-seven test applets into one code blob.

Each applet is linked by `chunker link` from its own entry symbols into its own
image, at its own address; the images are packed back to back (256-byte
aligned) into one blob starting at BLOB_BASE. The interpreter then sees one
read-only code region (one decode table), and any applet can read another's
rodata through a plain pointer. Writes guest-image/applets.bin and applets.rs.
"""
import os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CHUNKER = os.path.join(ROOT, "chunker", "target", "release", "chunker")
OUT = os.path.join(HERE, "guest-image")
BLOB_BASE = 0x0001_0000
ALIGN = 256

APPLETS = [
    ("h", ["H_IMPORTS", "h_hello", "h_timer", "h_nop_loop", "h_empty_loop", "h_uart_loop"], None),
    ("a", ["A_IMPORTS", "A_EXPORTS"], "A_EXPORTS"),
    ("a2", ["A2_IMPORTS", "A2_EXPORTS"], "A2_EXPORTS"),
    ("b", ["B_IMPORTS", "b_echo_once", "b_echo_loop", "b_local_loop", "b_loud", "b_recurse"], None),
    ("m", ["M_IMPORTS", "m_main"], None),
    ("s1", ["S1_IMPORTS", "S1_EXPORTS"], "S1_EXPORTS"),
    ("s2", ["S2_IMPORTS", "S2_EXPORTS"], "S2_EXPORTS"),
    ("s3", ["S3_IMPORTS"], None),
]


def link(inputs, entries, base, out):
    args = [CHUNKER, "link", "--base", hex(base), "-o", out]
    for e in entries:
        args += ["--entry", e]
    r = subprocess.run(args + inputs, capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"chunker link failed for {entries}: {r.stderr}")
    addrs = dict(re.findall(r"^(\S+) at (0x[0-9a-f]+)$", r.stdout, re.M))
    size = int(re.search(r"(\d+) bytes ->", r.stdout).group(1))
    return {k: int(v, 16) for k, v in addrs.items()}, size


def main():
    subprocess.run(["cargo", "build", "-q", "--release"], cwd=os.path.join(ROOT, "chunker"), check=True)
    env = dict(os.environ, PKG="applets", BUILD_STD="1")
    inputs = subprocess.run([os.path.join(ROOT, "guest", "build.sh")], env=env,
                            capture_output=True, text=True, check=True).stdout.split()
    os.makedirs(OUT, exist_ok=True)
    tmp = os.path.join(OUT, "tmp")
    blob = bytearray()
    rs = ["// Generated by meshops/build_applets.py. Do not edit.",
          f"pub const BLOB_BASE: u32 = {BLOB_BASE:#x};"]
    for name, entries, exports in APPLETS:
        off = (len(blob) + ALIGN - 1) // ALIGN * ALIGN
        blob.extend(b"\0" * (off - len(blob)))
        base = BLOB_BASE + off
        addrs, size = link(inputs, entries, base, tmp)
        blob.extend(open(tmp + ".bin", "rb").read())
        rs.append(f"pub mod {name} {{")
        rs.append(f"    pub const BASE: u32 = {base:#x};")
        rs.append(f"    pub const SIZE: u32 = {size};")
        rs.append(f"    pub const IMPORTS: u32 = {addrs[name.upper() + '_IMPORTS']:#x};")
        rs.append(f"    pub const EXPORTS: Option<u32> = {('Some(%#x)' % addrs[exports]) if exports else 'None'};")
        for e in entries:
            if not e.isupper():
                rs.append(f"    pub const {e[len(name) + 1:].upper()}: u32 = {addrs[e]:#x};")
        rs.append("}")
        print(f"applet {name}: {size} bytes at {base:#x}")
    blob.extend(b"\0" * (-len(blob) % 4))
    for ext in (".bin", ".rs"):
        os.remove(tmp + ext)
    open(os.path.join(OUT, "applets.bin"), "wb").write(blob)
    rs.append(f"pub const BLOB_LEN: usize = {len(blob)};")
    rs.append('pub static BLOB: [u8; BLOB_LEN] = *include_bytes!("applets.bin");')
    open(os.path.join(OUT, "applets.rs"), "w").write("\n".join(rs) + "\n")
    print(f"blob: {len(blob)} bytes at {BLOB_BASE:#x}")


if __name__ == "__main__":
    main()
